/** Порт Phoenix-сокета: корреляция по ref и таймауты живут в реализации */
export interface PhoenixRequestOptions {
  /**
   * Разрешает автоматический повтор после обрыва соединения или таймаута.
   *
   * По умолчанию повтор разрешён: подавляющее большинство вызовов это чтение, а чтение
   * идемпотентно, и запрос, потерянный на обрыве, обязан довестись сам, иначе каждый
   * вызывающий писал бы свой цикл повторов.
   *
   * КЛАСС ОТПРАВКИ ОБЯЗАН ПЕРЕДАВАТЬ `false` ЯВНО. Отправка необратима: сервер мог принять
   * кадр и не успеть ответить, и слепой повтор задвоил бы сообщение у собеседника.
   */
  retry?: boolean;
  timeoutMs?: number;
}

export interface PhoenixClient {
  request<T>(
    topic: string,
    event: string,
    payload: unknown,
    options?: PhoenixRequestOptions,
  ): Promise<T>;
  close(): Promise<void>;
}
