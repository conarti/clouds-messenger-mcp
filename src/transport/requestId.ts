/**
 * Идентификаторы, которые клиент придумывает сам: `sync_id` кадра отправки и `msg_id`
 * внутреннего события.
 *
 * Форма снята с живого клиента: канонический UUID v4 в нижнем регистре. Свой генератор
 * не пишется, потому что `randomUUID()` уже даёт криптостойкий источник, а `sync_id`
 * отвечает за идемпотентность отправки: совпадение двух значений означало бы, что
 * сервер посчитает разные сообщения одним.
 */
import { randomUUID } from 'node:crypto';

export function createRequestId(): string {
  return randomUUID();
}
