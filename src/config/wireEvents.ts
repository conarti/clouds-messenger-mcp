/**
 * Имена служебных событий и топиков сокета: лист без зависимостей.
 *
 * Модуль заведён ради направления зависимостей. Имена нужны сразу двум слоям: кодеку
 * кадров, который их собирает и разбирает, и авторизации, которая ловит кадр входа в
 * живом трафике браузера. Пока константы жили в кодеке, авторизация импортировала
 * транспорт, то есть верхний по замыслу слой тянул нижний ради одной строки.
 *
 * Здесь у модуля нет импортов вообще, поэтому его может читать кто угодно, ничего за
 * собой не приводя. Кодек реэкспортирует эти имена под своими прежними названиями:
 * существующие импорты кадров остаются на месте, а знание о проводе по-прежнему живёт
 * в разрешённых слоях (транспорт, протокол, крипто, конфиг).
 */

