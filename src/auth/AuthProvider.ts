/**
 * ПОРТ слоя авторизации: единственный шов, через который транспорт и крипто получают
 * всё необходимое для аутентифицированного вызова.
 *
 * За портом прячется Playwright: ни транспорт, ни крипто не знают, что где-то поднимается
 * браузер. Реализация появится отдельной историей, здесь объявляется только форма.
 */

/** Идентичность пользователя */
export interface Whoami {
  /** Мой huid: им подписан `from` во внутреннем событии и по нему отличается своё сообщение */
  huid: string;
}

/** Приватный ключ обмена (x25519) вместе с идентификатором своей публичной половины */
export interface PrivateKeyEntry {
  /** base64 приватного ключа x25519 */
  body: string;
  /** Идентификатор публичной половины: по нему идёт матч с `key.key_id` события */
  publicKeyId: string;
}

/** Ключи подписи (ed25519): ими подписывается исходящий payload */
export interface SignKeys {
  /** base64 приватного ключа ed25519 (64 байта) */
  privateBody: string;
  /** Идентификатор публичного ключа подписи: едет в кадре как `sign_key_id` */
  publicId: string;
}

/** Параметры сессии, которые сокет обязан вернуть серверу в query */
export interface WsParams {
  keyId: string;
  instanceId: string;
}

/**
 * Весь ключевой материал сессии одним объектом.
 *
 * `cts` и `rts` опциональны: в профиле присутствует не всякий вид ключа, и отсутствие
 * это штатное состояние, а не ошибка загрузки. Разбираться, какой из них подходит
 * к конкретному событию, обязан KeyStore, а не вызывающий.
 */
export interface KeyMaterial {
  privateKeys: {
    cts?: PrivateKeyEntry;
    rts?: PrivateKeyEntry;
  };
  signKeys: SignKeys;
  wsParams: WsParams;
}

export interface AuthProvider {
  /**
   * Свежий bearer. `forceRefresh` инвалидирует кэш и переавторизуется: это путь
   * восстановления после отказа авторизации, потому что токен из cookie протухает,
   * а протухший токен даёт не ошибку, а пустую выдачу.
   */
  getBearer(forceRefresh?: boolean): Promise<string>;
  /** Готовый заголовок Cookie для REST и хендшейка сокета */
  getCookieHeader(): Promise<string>;
  /** Идентичность пользователя */
  getWhoami(): Promise<Whoami>;
  /**
   * ЕДИНСТВЕННАЯ дверь к профилю и его IndexedDB.
   *
   * Никакой другой модуль не читает профиль напрямую: у ключевого материала обязан быть
   * ровно один владелец, иначе редакция логов, инвалидация кэша и границы доверия
   * размазываются по слоям, и утечка становится вопросом времени.
   */
  getKeyMaterial(): Promise<KeyMaterial>;
  /**
   * Сигнал, что текущие креды отвергнуты сервером. Реализация обязана сбросить кэш,
   * чтобы следующий вызов переавторизовался.
   */
  onAuthFailure(): Promise<void>;
}

/** Отказ авторизации: сигнал вызвать onAuthFailure() и повторить один раз */
export class AuthError extends Error {
  constructor(
    message: string,
    readonly kind: 'bearer' | 'protocol',
  ) {
    super(message);
    this.name = 'AuthError';
  }
}
