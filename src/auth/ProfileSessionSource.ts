import type { KeyMaterial } from './AuthProvider.js';

/**
 * Снимок профиля: всё, что даёт один подъём браузера, одним объектом.
 *
 * Собирается атомарно намеренно. Bearer, cookie и параметры сокета относятся к ОДНОЙ
 * сессии: взятые из разных подъёмов, они дают сочетание, которого никогда не было живьём,
 * а сервер отвечает на такое не ошибкой, а пустой выдачей, и причина не находится.
 */
export interface ProfileSession {
  /** Свежий токен доступа: тот, которым авторизуется сокет веб-клиента */
  bearer: string;
  /** Готовый заголовок Cookie для REST и хендшейка сокета */
  cookieHeader: string;
  /** Мой huid */
  huid: string;
  /** Ключевой материал сессии вместе с параметрами сокета */
  keyMaterial: KeyMaterial;
}

/**
 * Источник снимка профиля.
 *
 * Отдельный интерфейс, а не метод провайдера, потому что за ним стоит Playwright, а тестам
 * авторизации браузер не нужен: подложный источник со счётчиками доказывает схлопывание
 * параллельных входов, не поднимая Chromium.
 */
export interface ProfileSessionSource {
  /** Снимок профиля: первый вход сессии */
  load(): Promise<ProfileSession>;
  /**
   * Повторный снимок. Токен непрозрачен и обновляется самим веб-приложением
   * (POST /api/v1/ad_integration/token/refresh), поэтому обновление это повторный подъём
   * профиля, а не собственный запрос рефреша: см. решение Ф2 в findings.
   */
  refresh(): Promise<ProfileSession>;
}
